#!/usr/bin/env node
/**
 * gen-pilot-limits — the pilot limits, and the reads that measure them,
 * extracted from Rust into the control plane.
 *
 * Banzami Validation Studio (Phase C.5).
 *
 * The preflight has to answer "is there enough volume headroom to start this
 * run?". Answering it needs two things the financial core already owns: the
 * rolling-window CONSTANTS (owner decision D1) and the DEFINITION of merchant
 * credit volume.
 *
 * Restating either in Go would create a second source of financial truth — the
 * thing CLAUDE.md §2.1 and §19.2 exist to prevent. A preflight that measures
 * headroom differently from the engine that enforces it is worse than no
 * preflight: it would clear a run the ledger then refuses halfway through.
 *
 * So both are EXTRACTED, verbatim, from:
 *   core/compliance/src/pilot.rs          — the constants
 *   core/compliance/src/pilot_enforce.rs  — the read-only volume queries
 *
 * The generated file is checked in and drift-guarded. Changing a limit in Rust
 * without regenerating fails the build, which is the only acceptable coupling
 * between a policy and the surface that reports it.
 *
 *   node tools/gen-pilot-limits.mjs            # write
 *   node tools/gen-pilot-limits.mjs --check    # fail if it would change
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('.', import.meta.url)), '..');
const OUT = resolve(ROOT, 'services/admin-api/internal/validation/pilot_gen.go');
const CHECK = process.argv.includes('--check');

const die = (msg) => { console.error(`gen-pilot-limits: ${msg}`); process.exit(1); };

const pilot = readFileSync(resolve(ROOT, 'core/compliance/src/pilot.rs'), 'utf8');
const enforce = readFileSync(resolve(ROOT, 'core/compliance/src/pilot_enforce.rs'), 'utf8');

const CONSTANTS = [
  ['GLOBAL_ROLLING_24H_MINOR', 'GlobalRolling24hMinor', 'every merchant, trailing 24 hours'],
  ['GLOBAL_ROLLING_30D_MINOR', 'GlobalRolling30dMinor', 'every merchant, trailing 30 days'],
  ['MERCHANT_ROLLING_24H_MINOR', 'MerchantRolling24hMinor', 'one merchant, trailing 24 hours'],
  ['MERCHANT_ROLLING_30D_MINOR', 'MerchantRolling30dMinor', 'one merchant, trailing 30 days'],
];

const consts = CONSTANTS.map(([rust, go, note]) => {
  const m = pilot.match(new RegExp(`${rust}\\s*:\\s*i64\\s*=\\s*([0-9_]+)`));
  if (!m) die(`${rust} not found in core/compliance/src/pilot.rs`);
  return { go, value: m[1].replace(/_/g, ''), rust, note };
});

/**
 * Rust string literals here use `\` line continuations, which also swallow the
 * following line's leading whitespace. Reassemble the SQL exactly as sqlx sees
 * it, so the Go constant and the Rust constant are the same bytes.
 */
const extractSQL = (fnName) => {
  const at = enforce.indexOf(`async fn ${fnName}`);
  if (at < 0) die(`${fnName} not found in core/compliance/src/pilot_enforce.rs`);
  const body = enforce.slice(at);
  const open = body.indexOf('sqlx::query_scalar(');
  if (open < 0) die(`${fnName} has no query_scalar`);
  const q0 = body.indexOf('"', open);
  let i = q0 + 1, out = '';
  while (i < body.length) {
    const ch = body[i];
    if (ch === '\\') {
      const next = body[i + 1];
      if (next === '\n' || next === '\r') {          // line continuation
        i += 2;
        while (' \t\r\n'.includes(body[i])) i++;
        continue;
      }
      out += next === 'n' ? '\n' : next === 't' ? '\t' : next;
      i += 2;
      continue;
    }
    if (ch === '"') break;
    out += ch;
    i++;
  }
  if (!out.toUpperCase().includes('SELECT')) die(`${fnName}: extracted text is not a query`);
  return out;
};

const globalSQL = extractSQL('global_rolling_volume_minor');
const merchantSQL = extractSQL('merchant_rolling_volume_minor');

const lines = [
  '// Code generated by tools/gen-pilot-limits.mjs. DO NOT EDIT.',
  '//',
  '// Source of truth:',
  '//   core/compliance/src/pilot.rs          — the constants (owner decision D1)',
  '//   core/compliance/src/pilot_enforce.rs  — the read-only volume queries',
  '//',
  '// Extracted rather than restated. A preflight that measured headroom',
  '// differently from the engine that enforces it would clear a run the ledger',
  '// then refuses halfway through — worse than no preflight at all.',
  '//',
  '// Regenerate with: make gen-pilot-limits',
  '',
  'package validation',
  '',
];

for (const c of consts) {
  lines.push(`// ${c.go} is ${c.rust}: ${c.note}.`);
  lines.push(`const ${c.go} int64 = ${c.value}`);
  lines.push('');
}

lines.push('// QueryGlobalRollingVolume measures merchant-credit volume across EVERY');
lines.push('// merchant inside a rolling window. $1 is a Postgres interval literal.');
lines.push('// Read-only: it counts history, it never writes it.');
lines.push(`const QueryGlobalRollingVolume = ${JSON.stringify(globalSQL)}`);
lines.push('');
lines.push("// QueryMerchantRollingVolume measures ONE merchant's available account inside");
lines.push('// a rolling window. $1 is the account id, $2 the interval literal.');
lines.push(`const QueryMerchantRollingVolume = ${JSON.stringify(merchantSQL)}`);
lines.push('');

let out = lines.join('\n');
try {
  out = execFileSync('gofmt', [], { input: out, encoding: 'utf8', maxBuffer: 1 << 24 });
} catch (e) {
  die(`gofmt rejected the generated file: ${String(e.stderr || e.message).trim()}`);
}

if (CHECK) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== out) {
    console.error('✗ VALIDATION_PILOT_LIMITS_DRIFT=FAIL');
    console.error('  services/admin-api/internal/validation/pilot_gen.go no longer matches');
    console.error('  core/compliance/src/pilot{,_enforce}.rs. The preflight would measure');
    console.error('  headroom differently from the engine that enforces it.');
    console.error('  Fix: make gen-pilot-limits');
    process.exit(1);
  }
  console.log('✓ VALIDATION_PILOT_LIMITS_DRIFT=0');
  for (const c of consts) console.log(`  ${c.go} = ${c.value}`);
  process.exit(0);
}

writeFileSync(OUT, out);
console.log(`wrote ${OUT.replace(ROOT + '/', '')}`);
for (const c of consts) console.log(`  ${c.go} = ${c.value}`);
console.log(`  global query   ${globalSQL.slice(0, 60)}…`);
console.log(`  merchant query ${merchantSQL.slice(0, 60)}…`);
