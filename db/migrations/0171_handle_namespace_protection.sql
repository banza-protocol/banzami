-- Protect reserved and sensitive @banza handles — namespace protection.
--
-- @banza is the public identity of an account on Banzami. Before the public
-- Sandbox launch, normal signup (Consumer OR Business) must never be able to
-- take a handle that is internal/official, impersonates Banzami, or impersonates
-- an Angolan financial institution or a global payment brand. This is an
-- identity/security rule, enforced server-side in the ONE namespace table every
-- @banza creation already passes through: handle_registry (PK on handle = the
-- atomic, race-safe uniqueness point). No fake accounts are created to hold a
-- name — reservation is a property of the namespace itself.
--
-- Two things were missing and are added here:
--
--   1. A first-class PROTECTED class + provenance. owner_type gains 'PROTECTED'
--      (distinct from SYSTEM-reserved): a name that is NOT Banzami's and is only
--      ever assignable later through an explicit, RBAC-gated, audited operator
--      flow (no public bypass). Provenance columns record WHY a name is held
--      (category) and WHERE the list came from (source), so the registry can be
--      maintained when a bank is licensed/renamed/merged/withdrawn.
--
--   2. The canonical seed. The full set (internal, brand + impersonation combos,
--      ecosystem, BNA-authorized banks, global payment brands) is generated by
--      tools/gen-reserved-handles.mjs and guarded by tools/check-reserved-handles.mjs
--      so a fresh DB is born with the namespace protected and the list can never
--      silently drift (the A3-07 split-brain that let a Business apply for
--      @bna/@emis). Protection is by EXPLICIT handles and controlled combos only
--      — never substring rules that would block legitimate handles.
--
-- Account-deletion handle retirement (0168) is unchanged: a deleted handle stays
-- a non-reusable tombstone. Reserved/protected/retired/allocated all read as a
-- single neutral "unavailable" to the public (no enumeration of which, or whose).

-- 1. First-class PROTECTED class + provenance -------------------------------
ALTER TABLE handle_registry DROP CONSTRAINT IF EXISTS handle_registry_owner_type_check;
ALTER TABLE handle_registry
  ADD CONSTRAINT handle_registry_owner_type_check
  CHECK (owner_type IN ('CONSUMER', 'MERCHANT', 'SYSTEM', 'APPLICATION', 'PROTECTED'));

ALTER TABLE handle_registry ADD COLUMN IF NOT EXISTS protect_category TEXT;
ALTER TABLE handle_registry ADD COLUMN IF NOT EXISTS protect_source   TEXT;

COMMENT ON COLUMN handle_registry.protect_category IS
  'Why a reserved/protected handle is held: internal | brand | brand-impersonation | ecosystem | bank | payment-brand | impersonation. NULL for owned/retired rows.';
COMMENT ON COLUMN handle_registry.protect_source IS
  'Provenance of a protected entry (e.g. the BNA authorized-banking registry). A PROTECTED name is NOT owned by Banzami.';

